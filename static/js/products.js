window.createProductCardHTML = function (product) {
    const badgeHTML = product.isNew
        ? `<span class="product-card-badge">SS26 // NEW</span>`
        : `<span class="product-card-badge">${product.code}</span>`;

    const defaultSize = (product.sizes && product.sizes.includes("L")) ? "L" : (product.sizes[0] || "M");

    return `
    <article class="product-card" data-product-id="${product.id}">
        <div class="product-card-media">
            ${badgeHTML}
            <a href="product.html?id=${product.id}" aria-label="View ${product.name}">
                <img src="${product.image}" alt="${product.name}" class="img-primary" loading="lazy">
                <img src="${product.image2 || product.image}" alt="${product.name} alternate view" class="img-secondary" loading="lazy">
            </a>
            <button type="button" class="quick-add-btn"
                    onclick="window.NFCart.quickAdd('${product.id}', '${defaultSize}', this)"
                    aria-label="Quick add ${product.name} to cart">
                <span class="qa-label">+ QUICK ADD (${defaultSize})</span>
                <span class="arrow-icon">→</span>
            </button>
        </div>
        <div class="product-card-info">
            <div class="product-card-top">
                <a href="product.html?id=${product.id}" class="product-card-title">${product.code} — ${product.name}</a>
                <span class="product-card-price">$${product.price}</span>
            </div>
            <div class="product-card-sub">
                <span>${product.subtitle}</span>
                <span>${product.color}</span>
            </div>
        </div>
    </article>
    `;
};
